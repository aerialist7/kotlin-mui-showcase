private enum class IconStyle(val label: String) {
    Filled("Filled"), Outlined("Outlined"), Rounded("Rounded"), TwoTone("Two Tone"), Sharp("Sharp")
}

val IconsShowcase = FC<Props> {
    var searchQuery by useState("")
    var selectedStyle by useState(IconStyle.Filled)

    val filtered = ICONS.filter { it.name.contains(searchQuery, ignoreCase = true) }

    Box {
        sx {
            display = Display.flex
            flexDirection = FlexDirection.column
            gap = 16.px
        }

        // Search + style filter toolbar
        Box {
            sx {
                display = Display.flex
                flexDirection = FlexDirection.row
                gap = 16.px
                alignItems = AlignItems.center
                flexWrap = FlexWrap.wrap
            }

            TextField {
                id = ElementId("icon-search")
                label = ReactNode("Search icons")
                size = small
                value = searchQuery
                asDynamic().onChange = { event: dynamic -> searchQuery = event.target.value as String }
                sx { minWidth = 220.px }
            }

            ToggleButtonGroup {
                exclusive = true
                value = selectedStyle.name
                asDynamic().onChange = { _: dynamic, v: dynamic ->
                    if (v != null) {
                        selectedStyle = IconStyle.valueOf(v.toString())
                    }
                }
                size = small

                IconStyle.entries.forEach { style ->
                    ToggleButton {
                        key = style.name
                        value = style.name
                        +style.label
                    }
                }
            }
        }

        // Icons grid
        Typography {
            variant = TypographyVariant.Companion.body2
            asDynamic().color = "text.secondary"
            +"${filtered.size} icons"
        }

        Box {
            sx {
                display = Display.grid
                asDynamic().gridTemplateColumns = "repeat(auto-fill, minmax(80px, 1fr))"
                gap = 8.px
            }

            filtered.forEach { entry ->
                val iconFC = when (selectedStyle) {
                    IconStyle.Filled -> entry.filled
                    IconStyle.Outlined -> entry.outlined
                    IconStyle.Rounded -> entry.rounded
                    IconStyle.TwoTone -> entry.twoTone
                    IconStyle.Sharp -> entry.sharp
                }

                Box {
                    key = entry.name
                    sx {
                        display = Display.flex
                        flexDirection = FlexDirection.column
                        alignItems = AlignItems.center
                        justifyContent = JustifyContent.center
                        padding = 8.px
                        borderRadius = 4.px
                        gap = 4.px
                        hover {
                            backgroundColor = Color("action.hover")
                        }
                    }

                    Tooltip {
                        title = ReactNode(entry.name)
                        (iconFC.unsafeCast<FC<Props>>())()
                    }

                    Typography {
                        variant = TypographyVariant.Companion.caption
                        sx {
                            textAlign = TextAlign.center
                            overflow = Overflow.hidden
                            asDynamic().textOverflow = "ellipsis"
                            whiteSpace = WhiteSpace.nowrap
                            width = 72.px
                        }
                        +entry.name
                    }
                }
            }
        }
    }
}